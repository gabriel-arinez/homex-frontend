import { expect, test, type Page } from '@playwright/test'
import { resolve } from 'node:path'
test.setTimeout(60_000)
const file = (color: string) => resolve('src/tests/fixtures/galerias', color + '.png')
async function login(page: Page) {
  await page.goto('/login')
  await page.getByLabel('Usuario').fill(process.env.HOMEX_GALLERY_USERNAME ?? 'gallery-e2e-seller')
  await page
    .getByLabel('Contraseña')
    .fill(process.env.HOMEX_GALLERY_PASSWORD ?? 'gallery-integration-only')
  await page.getByRole('button', { name: 'Ingresar' }).click()
  await expect(page).toHaveURL(/\/resumen$/)
}
async function step(page: Page, label: string) {
  await page
    .getByRole('navigation', { name: 'Apartados del mueble a pedido' })
    .getByRole('button', { name: label })
    .click()
}
for (const width of [360, 1280]) {
  test(`Galería real de vendedor: catálogo, portada y orden a ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await login(page)
    await page.goto('/productos/nuevo')
    const name = `Galería E2E ${width} ${Date.now()}`
    await page.locator('input[name=nombre]').fill(name)
    await page.locator('select[name=categoria]').selectOption({ label: 'Otro producto' })
    await page.locator('input[name=sku]').fill(`GAL-${width}-${Date.now()}`)
    await page.locator('select[name=unidad]').selectOption({ label: 'Pieza' })
    await page.locator('input[name=precio]').fill('150')
    await expect(page.getByLabel('Agregar imágenes', { exact: true })).toBeEnabled()
    await page
      .getByLabel('Agregar imágenes', { exact: true })
      .setInputFiles([file('red'), file('blue')])
    await expect(page.getByRole('heading', { name: 'Galería de imágenes 2/8' })).toBeVisible()
    await page.getByRole('button', { name: 'Gestionar imágenes', exact: true }).click()
    const manager = page.getByRole('dialog', { name: 'Gestionar imágenes', exact: true })
    await manager
      .locator('article')
      .nth(1)
      .getByRole('button', { name: 'Establecer principal' })
      .click()
    await manager.locator('article').nth(1).getByRole('button', { name: 'Mover antes' }).click()
    await manager.getByRole('button', { name: 'Cerrar', exact: true }).click()
    await page.getByRole('button', { name: 'Guardar producto', exact: true }).click()
    await expect(page).toHaveURL(/\/productos(?:\?|$)/)
    await page.getByRole('link', { name, exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Galería de imágenes 2/8' })).toBeVisible()
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Galería de imágenes 2/8' })).toBeVisible()
    await page.getByRole('button', { name: 'Ampliar imagen principal' }).click()
    const viewer = page.getByRole('dialog', { name: 'Visor de imágenes' })
    await expect(viewer.locator('.large img')).toHaveAttribute('alt', 'blue.png')
    await viewer.getByRole('button', { name: 'Siguiente' }).click()
    await expect(viewer.locator('.large img')).toHaveAttribute('alt', 'red.png')
    await viewer.getByRole('button', { name: 'Cerrar', exact: true }).click()
    await page.getByRole('button', { name: 'Gestionar imágenes', exact: true }).click()
    await manager
      .locator('article')
      .first()
      .getByRole('button', { name: 'Eliminar', exact: true })
      .click()
    await page
      .getByRole('dialog', { name: 'Eliminar imagen' })
      .getByRole('button', { name: 'Eliminar', exact: true })
      .click()
    await expect(manager.locator('article')).toHaveCount(1)
    await expect(manager.locator('article').first()).toContainText('Principal')
    await manager.getByRole('button', { name: 'Cerrar', exact: true }).click()
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Galería de imágenes 1/8' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
test('Galería real de mueble: borrador restaurado y vinculación integral', async ({ page }) => {
  await login(page)
  await page.goto('/proformas/nueva')
  await page.getByRole('button', { name: 'Añadir ítem' }).click()
  await page.getByRole('button', { name: 'Mueble a pedido' }).click()
  await page.getByLabel('Nombre comercial del mueble').fill('Mueble con referencias E2E')
  await step(page, 'Imágenes')
  await expect(page.getByLabel('Agregar imágenes', { exact: true })).toBeEnabled()
  await page
    .getByLabel('Agregar imágenes', { exact: true })
    .setInputFiles([file('red'), file('green')])
  await expect(page.getByRole('heading', { name: 'Imágenes del mueble 2/8' })).toBeVisible()
  await step(page, 'Precio')
  await page.getByLabel('Precio unitario negociado (BOB)').fill('700')
  await step(page, 'Revisar')
  await expect(page.getByRole('heading', { name: 'Imágenes del mueble 2/8' })).toBeVisible()
  await page.getByRole('button', { name: 'Agregar mueble a la proforma', exact: true }).click()
  await page.reload()
  await expect(page.getByText('Mueble con referencias E2E', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Guardar borrador', exact: true }).click()
  await expect(page).toHaveURL(/\/proformas\/\d+\/editar$/)
  await page.reload()
  const menu = page.getByRole('button', { name: /Acciones.*Mueble con referencias/ })
  await menu.click()
  await page.getByRole('menuitem', { name: /ficha|configurar|técnica/i }).click()
  await step(page, 'Imágenes')
  await expect(page.getByRole('heading', { name: 'Imágenes del mueble 2/8' })).toBeVisible()
  await page.getByRole('button', { name: 'Gestionar imágenes', exact: true }).click()
  const manager = page.getByRole('dialog', { name: 'Gestionar imágenes', exact: true })
  await manager
    .locator('article')
    .nth(1)
    .getByRole('button', { name: 'Establecer principal' })
    .click()
  await expect(manager.locator('article').nth(1)).toContainText('Principal')
  await manager.getByRole('button', { name: 'Cerrar', exact: true }).click()
  await step(page, 'Revisar')
  await page.getByRole('button', { name: 'Agregar mueble a la proforma', exact: true }).click()
  await page.getByRole('button', { name: /Acciones.*Mueble con referencias/ }).click()
  await page.getByRole('menuitem', { name: 'Duplicar mueble', exact: true }).click()
  await expect(page.getByLabel('Nombre comercial del mueble')).toBeVisible()
  await page.getByLabel('Nombre comercial del mueble').fill('Copia con referencias E2E')
  await step(page, 'Imágenes')
  await expect(page.getByRole('heading', { name: 'Imágenes del mueble 2/8' })).toBeVisible()
  await step(page, 'Revisar')
  await page.getByRole('button', { name: 'Agregar mueble a la proforma', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar borrador', exact: true }).click()
  await expect(page.getByText('Borrador guardado.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Acciones.*Mueble con referencias/ }).click()
  await page.getByRole('menuitem', { name: 'Eliminar', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar borrador', exact: true }).click()
  await expect(page.getByText('Borrador guardado.', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /Acciones.*Copia con referencias/ }).click()
  await page.getByRole('menuitem', { name: 'Ficha técnica', exact: true }).click()
  await step(page, 'Imágenes')
  await expect(page.getByRole('heading', { name: 'Imágenes del mueble 2/8' })).toBeVisible()
  await expect(
    page.getByRole('button', { name: 'Ampliar imagen principal' }).locator('img'),
  ).toHaveAttribute('alt', 'green.png')
})
